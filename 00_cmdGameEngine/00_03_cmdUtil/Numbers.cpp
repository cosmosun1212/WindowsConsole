// 숫자 num을 (x, y) 위치에 ch 문자로 color 색상으로 그리는 함수
void DrawNumber(int x, int y, int num, const wchar_t* ch, unsigned short color)
{
	if (num < 0 || num > 9) return; // num이 0~9 범위를 벗어나면 함수 종료
	 
	SetScreenColor(color); 

	// Number 배열에서 num에 해당하는 패턴을 읽어서 (x, y) 위치에 ch 문자로 그리기	
	for (int iy = 0; iy < 5; iy++) 
	{
		// Number[num][iy][ix]가 1이면 ch 문자를, 0이면 공백을 그리도록 처리
		for (int ix = 0; ix < 3; ix++)
		{
			// Number 배열에서 num에 해당하는 패턴을 읽어서 (x, y) 위치에 ch 문자로 그리기
			if (Number[num][iy][ix] == 1) 
			{
				ScreenPrint(x + ix, y + iy, ch); /// Number 배열에서 num에 해당하는 패턴을 읽어서 (x, y) 위치에 ch 문자로 그리기 (1인 경우)
			}
			else
			{
				ScreenPrint(x + ix, y + iy, L"　"); // 0인 경우에는 공백 문자로 그리기 (유니코드 전각 공백 U+3000)
			}
		}
	}
}

